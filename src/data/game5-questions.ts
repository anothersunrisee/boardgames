/**
 * Mengambil paket 4 seri pertanyaan berantai untuk 1 tim.
 * - Menjamin 4 soal berasal dari 4 KATEGORI BERBEDA (Sejarah, IPA, Antariksa, dll.)
 * - Menjamin soal yang sudah pernah muncul (usedIds) TIDAK AKAN MUNCUL LAGI.
 * - Jika soal yang belum terpakai menipis (< 4), sistem me-recycle dari bank lengkap.
 */
export function getRandomTriviaChain(count: number = 4, usedIds: number[] = []): TriviaQuestion[] {
  const unusedPool = TRIVIA_QUESTIONS.filter((q) => !usedIds.includes(q.id));
  const activePool = unusedPool.length >= count ? unusedPool : TRIVIA_QUESTIONS;

  // Kelompokkan bank soal aktif per kategori
  const byCategory: Record<string, TriviaQuestion[]> = {};
  activePool.forEach((q) => {
    if (!byCategory[q.category]) byCategory[q.category] = [];
    byCategory[q.category].push(q);
  });

  const categoryKeys = Object.keys(byCategory).sort(() => Math.random() - 0.5);
  const picked: TriviaQuestion[] = [];
  const pickedCategorySet = new Set<string>();

  // Langkah 1: Ambil 1 soal dari kategori berbeda untuk tiap seri
  for (const cat of categoryKeys) {
    if (picked.length >= count) break;
    const catQuestions = byCategory[cat];
    if (catQuestions && catQuestions.length > 0) {
      const randomIdx = Math.floor(Math.random() * catQuestions.length);
      picked.push(catQuestions[randomIdx]);
      pickedCategorySet.add(cat);
    }
  }

  // Langkah 2: Jika masih kurang (edge case), ambil acak dari pool tersisa
  if (picked.length < count) {
    const pickedIds = new Set(picked.map((p) => p.id));
    const remainder = activePool.filter((q) => !pickedIds.has(q.id)).sort(() => Math.random() - 0.5);
    for (const r of remainder) {
      if (picked.length >= count) break;
      picked.push(r);
    }
  }

  return picked;
}

export function getQuestionsByCategory(category: TriviaCategory): TriviaQuestion[] {
  return TRIVIA_QUESTIONS.filter((q) => q.category === category);
}
